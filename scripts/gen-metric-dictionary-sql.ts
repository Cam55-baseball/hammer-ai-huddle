/**
 * Writes supabase/seed/release0_metric_dictionary.sql from the one dictionary
 * (supabase/functions/_shared/ledger/metricDictionary.ts). Idempotent upserts; never deletes.
 * Run: bun scripts/gen-metric-dictionary-sql.ts
 */
import { writeFileSync } from "node:fs";
import { ALIASES, METRICS, conversionRows } from "../supabase/functions/_shared/ledger/metricDictionary";

const q = (v: unknown) => (v == null ? "NULL" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);

export function dictionarySql(): string {
  const out: string[] = ["-- GENERATED by scripts/gen-metric-dictionary-sql.ts — do not edit by hand.", "BEGIN;"];
  for (const [to, from, f] of conversionRows()) {
    out.push(`INSERT INTO public.metric_unit_conversions (to_unit, from_unit, factor) VALUES (${q(to)}, ${q(from.toLowerCase())}, ${f}) ON CONFLICT (to_unit, from_unit) DO UPDATE SET factor = EXCLUDED.factor;`);
  }
  for (const m of METRICS) {
    out.push(`INSERT INTO public.measurement_definitions (metric_key, unit, athlete_label, display_name, definition, published_source, source_status, sport, higher_is_better, physical_min, physical_max, gt_tolerance, gt_device, required_fps, category, privacy_class, in_app_only, is_canonical, notes)
VALUES (${q(m.key)}, ${q(m.unit)}, ${q(m.label)}, ${q(m.label)}, ${q(m.definition)}, ${q(m.source)}, ${q(m.source ? "published" : "proposed")}, ${q(m.sport)}, ${q(m.higherIsBetter)}, ${q(m.physMin)}, ${q(m.physMax)}, ${q(m.gtTolerance)}, ${q(m.gtDevice)}, ${q(m.requiredFps)}, ${q(m.category)}, ${q(m.privacy)}, ${q(m.inAppOnly)}, true, 'Release 0 dictionary')
ON CONFLICT (metric_key) DO UPDATE SET unit = EXCLUDED.unit, display_name = EXCLUDED.display_name, definition = EXCLUDED.definition, published_source = EXCLUDED.published_source,
  source_status = EXCLUDED.source_status, sport = EXCLUDED.sport, higher_is_better = EXCLUDED.higher_is_better, physical_min = EXCLUDED.physical_min, physical_max = EXCLUDED.physical_max,
  gt_tolerance = EXCLUDED.gt_tolerance, gt_device = EXCLUDED.gt_device, required_fps = EXCLUDED.required_fps, category = EXCLUDED.category, privacy_class = EXCLUDED.privacy_class,
  in_app_only = EXCLUDED.in_app_only, is_canonical = true, updated_at = now();`);
  }
  for (const a of ALIASES) {
    out.push(`INSERT INTO public.metric_aliases (alias_key, canonical_key, alias_unit, naming_system, note) VALUES (${q(a.alias)}, ${q(a.key)}, ${q(a.unit)}, ${q(a.system)}, ${q(a.note ?? null)})
ON CONFLICT (alias_key) DO UPDATE SET canonical_key = EXCLUDED.canonical_key, alias_unit = EXCLUDED.alias_unit, naming_system = EXCLUDED.naming_system, note = EXCLUDED.note;`);
  }
  out.push("COMMIT;");
  return out.join("\n") + "\n";
}

if (import.meta.main) {
  writeFileSync("supabase/seed/release0_metric_dictionary.sql", dictionarySql());
  console.log(`metrics=${METRICS.length} aliases=${ALIASES.length} conversions=${conversionRows().length}`);
}
