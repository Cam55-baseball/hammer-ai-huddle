/**
 * Writes supabase/seed/release0_metric_dictionary.sql from the one dictionary
 * (supabase/functions/_shared/ledger/metricDictionary.ts). Idempotent upserts; never deletes.
 * Run: bun scripts/gen-metric-dictionary-sql.ts
 */
import { writeFileSync } from "node:fs";
import { ALIASES, METRICS, conversionRows } from "../supabase/functions/_shared/ledger/metricDictionary";

export function dictionarySql(): string {
  const lit = (v: unknown) => `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  const conv = conversionRows().map(([to, from, f]) => ({ t: to, f: from.toLowerCase(), x: f }));
  const defs = METRICS.map((m) => ({ k: m.key, u: m.unit, l: m.label, d: m.definition, s: m.source, sp: m.sport, h: m.higherIsBetter,
    mn: m.physMin, mx: m.physMax, gt: m.gtTolerance, gd: m.gtDevice, fps: m.requiredFps, c: m.category, p: m.privacy, ia: m.inAppOnly }));
  const al = ALIASES.map((a) => ({ a: a.alias, k: a.key, u: a.unit, s: a.system, n: a.note ?? null }));
  return [
    "-- GENERATED by scripts/gen-metric-dictionary-sql.ts from _shared/ledger/metricDictionary.ts. Idempotent upserts; never deletes.",
    `INSERT INTO public.metric_unit_conversions (to_unit, from_unit, factor) SELECT t, f, x FROM jsonb_to_recordset(${lit(conv)}) AS r(t text, f text, x double precision)
ON CONFLICT (to_unit, from_unit) DO UPDATE SET factor = EXCLUDED.factor;`,
    `INSERT INTO public.measurement_definitions (metric_key, unit, athlete_label, display_name, definition, published_source, source_status, sport, higher_is_better,
  physical_min, physical_max, gt_tolerance, gt_device, required_fps, category, privacy_class, in_app_only, is_canonical, notes)
SELECT k, u, l, l, d, s, CASE WHEN s IS NULL THEN 'proposed' ELSE 'published' END, sp, h, mn, mx, gt, gd, fps, c, p, ia, true, 'Release 0 dictionary'
FROM jsonb_to_recordset(${lit(defs)}) AS r(k text, u text, l text, d text, s text, sp text, h boolean, mn double precision, mx double precision,
  gt double precision, gd text, fps integer, c text, p text, ia boolean)
ON CONFLICT (metric_key) DO UPDATE SET unit = EXCLUDED.unit, display_name = EXCLUDED.display_name, definition = EXCLUDED.definition,
  published_source = EXCLUDED.published_source, source_status = EXCLUDED.source_status, sport = EXCLUDED.sport, higher_is_better = EXCLUDED.higher_is_better,
  physical_min = EXCLUDED.physical_min, physical_max = EXCLUDED.physical_max, gt_tolerance = EXCLUDED.gt_tolerance, gt_device = EXCLUDED.gt_device,
  required_fps = EXCLUDED.required_fps, category = EXCLUDED.category, privacy_class = EXCLUDED.privacy_class, in_app_only = EXCLUDED.in_app_only,
  is_canonical = true, updated_at = now();`,
    `INSERT INTO public.metric_aliases (alias_key, canonical_key, alias_unit, naming_system, note) SELECT a, k, u, s, n
FROM jsonb_to_recordset(${lit(al)}) AS r(a text, k text, u text, s text, n text)
ON CONFLICT (alias_key) DO UPDATE SET canonical_key = EXCLUDED.canonical_key, alias_unit = EXCLUDED.alias_unit, naming_system = EXCLUDED.naming_system, note = EXCLUDED.note;`,
  ].join("\n") + "\n";
}

if (import.meta.main) {
  writeFileSync("supabase/seed/release0_metric_dictionary.sql", dictionarySql());
  console.log(`metrics=${METRICS.length} aliases=${ALIASES.length} conversions=${conversionRows().length}`);
}
