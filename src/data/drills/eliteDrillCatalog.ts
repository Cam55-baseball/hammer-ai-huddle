/** Teaching level — matches the existing feel → iso → constraint → transfer ladder. */
export type EliteDrillLevel = "feel" | "iso" | "constraint" | "transfer";

export interface EliteDrill {
  id: string;
  name: string;
  category: Extract<VideoCategory, "hitting" | "throwing" | "pitching">;
  /** Sports this drill is legal for. */
  sports: VideoSport[];
  /** Constrained sub-skill from the video taxonomy for this sport/category. */
  subSkill: string;
  level: EliteDrillLevel;
  /** What the drill is actually fixing, in coach language. */
  fixes: string;
  setup: string;
  steps: string[];
  cues: string[];
  dosage: string;
  equipment: string[];
  /** `violations_detected` keys emitted by analyze-video. */
  violationKeys: string[];
  /** PIE V2 signal ids this drill targets. */
  pieV2Signals: PieV2SignalId[];
  /** movement_pattern taxonomy keys (video_tag_taxonomy). */
  movementPatterns: string[];
}

