/**
 * Elite prescription drill catalog — hitting, throwing, pitching.
 *
 * Every entry is a real, widely-coached drill (no invented content) and is
 * tagged into the systems that already exist in this codebase so prescription
 * works end to end:
 *
 *  - `violationKeys`   → `analyze-video` `violations_detected` flags
 *  - `pieV2Signals`    → `PieV2SignalId` (src/lib/pieV2/types.ts)
 *  - `movementPatterns`→ seeded `video_tag_taxonomy` movement_pattern keys
 *  - `category`/`subSkill` → constrained video taxonomy
 *    (src/lib/videoCategoricalTaxonomy.ts)
 *
 * Presentation/content only. No scoring, no organism truth authored here.
 */
import type { VideoCategory, VideoSport } from "@/lib/videoCategoricalTaxonomy";
