export function eliteDrillsForCategory(
  category: EliteDrill["category"],
  sport: VideoSport,
): EliteDrill[] {
  return ELITE_DRILL_CATALOG.filter(
    (d) => d.category === category && d.sports.includes(sport),
  );
}
